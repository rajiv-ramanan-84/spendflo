// Writes supabase/seed_skill.sql: the campaign skill plus the outbound reference
// docs as the next skill version, only when the text changed.
// Run after editing docs/flo-campaign-engine-SKILL.md or docs/skill-reference/*:
//   node scripts/gen-skill-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(p, import.meta.url), "utf8").trim();
const skill = read("../docs/flo-campaign-engine-SKILL.md");
const refDir = new URL("../docs/skill-reference/", import.meta.url);
const refs = readdirSync(refDir).filter((f) => /\.(md|txt)$/.test(f) && f !== "README.md").sort();

// App conventions Claude must know. Kept here, next to the skill, so the skill file stays the team's own.
const appNotes = [
  "# How the app sends data",
  "",
  "- Contacts are referenced as c1, c2 and so on. Use exactly those refs in contact_ref, from_contact and skipped_contacts.",
  "- has_phone: true means a direct line exists. The number itself is withheld for privacy, so plan calls where has_phone is true and do not flag the missing number. Where it is false, prefer email or LinkedIn over a call.",
  "- Never claim shared connections, a past meeting or an earlier conversation unless the request's data shows it. Copy that does is blocked before launch.",
  "- Keep review.flags to what the owner must decide or fix before launch. Put softer observations in main_weakness or rationale.",
  "- step_index counts from 1, and the app dates triggered tracks and enforces caps itself. Do not flag how the app counts or schedules; flag only what a person must do.",
].join("\n");

const reference = [
  "# Reference material",
  "",
  "Internal Spendflo documents, dated 30 October 2026. Use them for positioning, evidence boundaries, claims to avoid, persona review and the Mattel and Sonoco history. They do not change the output format or the rules above, and where they conflict with the account data in the request, the request wins. Never present a planned milestone, illustrative sample or customer activity as a Flo result. Keep Datavant anonymous as \"a Coupa customer\" unless the request says naming is approved. Copy in these documents (such as em dashes in old drafts) is history, not a style to copy.",
  ...refs.map((f) => `\n## ${f.replace(/^\d+-/, "").replace(/\.(md|txt)$/, "")}\n\n${read(`../docs/skill-reference/${f}`)}`),
].join("\n");

const body = `${skill}\n\n${appNotes}\n\n${reference}\n`;
if (body.includes("$skill$")) throw new Error("Skill text contains the dollar-quote tag");
const sql = `-- Generated by scripts/gen-skill-seed.mjs from docs/flo-campaign-engine-SKILL.md
-- and docs/skill-reference/*. Adds the next skill version only when the text
-- differs from the latest one, so it is safe to re-run. Later edits happen in Settings.
insert into skill_versions (version_no, body)
select coalesce(max(version_no), 0) + 1, $skill$${body}$skill$
from skill_versions
having coalesce((select body from skill_versions order by version_no desc limit 1), '') <> $skill$${body}$skill$;
`;
writeFileSync(new URL("../supabase/seed_skill.sql", import.meta.url), sql);
console.log(`wrote seed_skill.sql: skill ${skill.length} chars + ${refs.length} reference docs, ${body.length} chars total`);
