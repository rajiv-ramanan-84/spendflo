// Writes supabase/seed_skill.sql: the campaign skill as skill version 1, if none exists.
// Run after editing docs/flo-campaign-engine-SKILL.md: node scripts/gen-skill-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
const body = readFileSync(new URL("../docs/flo-campaign-engine-SKILL.md", import.meta.url), "utf8");
if (body.includes("$skill$")) throw new Error("Skill text contains the dollar-quote tag");
const sql = `-- Generated by scripts/gen-skill-seed.mjs from docs/flo-campaign-engine-SKILL.md.
-- Seeds version 1 only when no skill exists; later edits happen in Settings.
insert into skill_versions (version_no, body)
select 1, $skill$${body}$skill$
where not exists (select 1 from skill_versions);
`;
writeFileSync(new URL("../supabase/seed_skill.sql", import.meta.url), sql);
console.log(`wrote seed_skill.sql (${body.length} chars)`);
