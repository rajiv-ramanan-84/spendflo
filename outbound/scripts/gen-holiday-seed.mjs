// Regenerates supabase/seed_holidays.sql: US federal (prospect calendar) and
// India national holidays (team calendar) for the current and next year.
// Run: node scripts/gen-holiday-seed.mjs 2026 2027
import Holidays from "date-holidays";
import { writeFileSync } from "node:fs";

const years = process.argv.slice(2).map(Number);
if (!years.length) throw new Error("usage: node scripts/gen-holiday-seed.mjs 2026 2027");

const us = new Holidays("US");
const rows = [];
for (const y of years) {
  const seen = new Set();
  for (const h of us.getHolidays(y)) {
    const date = h.date.slice(0, 10);
    if (h.type !== "public" || seen.has(date)) continue;
    seen.add(date);
    rows.push(["US", date, h.name]);
  }
  // India national holidays every company observes. The full Spendflo list
  // (Diwali, Holi and so on) is added by an admin in Settings.
  rows.push(["IN_TEAM", `${y}-01-26`, "Republic Day"]);
  rows.push(["IN_TEAM", `${y}-08-15`, "Independence Day (India)"]);
  rows.push(["IN_TEAM", `${y}-10-02`, "Gandhi Jayanti"]);
}

const esc = (s) => s.replace(/'/g, "''");
const sql = [
  "-- Generated by scripts/gen-holiday-seed.mjs. Do not edit by hand.",
  `-- Years: ${years.join(", ")}. Safe to re-run.`,
  "insert into holidays (calendar, date, name, source) values",
  rows.map(([c, d, n]) => `  ('${c}', '${d}', '${esc(n)}', 'preloaded')`).join(",\n"),
  "on conflict (calendar, date) do nothing;",
  "",
].join("\n");
writeFileSync(new URL("../supabase/seed_holidays.sql", import.meta.url), sql);
console.log(`wrote ${rows.length} holidays`);
